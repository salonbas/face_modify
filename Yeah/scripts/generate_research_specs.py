#!/usr/bin/env python3
"""Render checked research specifications from frozen JSON artifacts."""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = ("arcface", "facenet", "adaface", "mobilefacenet", "magface")


def load(path: str) -> dict:
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def sha(path: str) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def calibration() -> str:
    manifest = load("models/checkpoint_manifest.json")
    lines = [
        "# Calibration and thresholds",
        "",
        "Generated by `scripts/generate_research_specs.py` from frozen calibration JSON and checkpoint manifest. Last verified: 2026-10-29. Do not edit numeric values here; update the authority artifacts and regenerate.",
        "",
        "Decision: same identity iff cosine ≥ threshold. Primary operating point is `far_1e-2` (target FAR 0.01). See `advface/calibration.py`: sort valid train impostor scores descending; take the score at zero-based index floor(0.01×N), then `nextafter(score,+∞)`. Test pairs are evaluated only after threshold selection. Missing detections are excluded from calibration score denominators and retained as errors in metadata.",
        "",
        "| Model / checkpoint | v2 threshold | Train FAR / TAR | Held-out FAR / TAR | Checkpoint SHA-256 |",
        "| --- | ---: | ---: | ---: | --- |",
    ]
    for name in NAMES:
        path = f"results/calibration/{name}_lfw_v2/thresholds.json"
        t = load(path)["far_1e-2"]
        d, h = t["development"], t["held_out_test"]
        lines.append(f"| {name} / {manifest[name]['backbone']} | {t['threshold']:.12g} | {d['fp']}/{d['fp']+d['tn']}={d['far']:.4%} / {d['tp']}/{d['tp']+d['fn']}={d['tar']:.4%} | {h['fp']}/{h['fp']+h['tn']}={h['far']:.4%} / {h['tp']}/{h['tp']+h['fn']}={h['tar']:.4%} | `{manifest[name]['sha256']}` |")
    lines += [
        "", "## Authority and isolation", "",
        "Calibration v2 uses `data/datasets/lfw/evaluation_splits/v2/calibration_pairs/dev_train.csv` for selection and `dev_test.csv` for held-out evaluation. The v2 split audit records zero attack/calibration identity and image overlap, and zero Development/OOS identity and A/B image overlap. Development has 100 identities; OOS has 228 and has not been used for model selection. Check `data/datasets/lfw/evaluation_splits/v2/audit.json` before interpreting results.",
        "",
        "Clean eligible means both images yield a valid embedding and clean A/B cosine ≥ that model's v2 threshold. Detection failure or clean cosine below threshold never counts as attack success. For common-eligible comparisons, all five models must be eligible on the same identity. `advface/evaluation/multi_victim.py` is the implementation authority.",
        "",
        "Calibration v1 supported the frozen 20-person v3 ArcFace/FaceNet baseline. Its FaceNet threshold is 0.40478909015655523; v2 recalibrates FaceNet to 0.4088586568832398 after excluding overlapping attack identities. ArcFace remains 0.14072093367576602. Do not apply v2 values retroactively to v3 results. The old split has calibration identity overlap with attack reserve/test; see the v2 audit for exact identities. V1 artifacts remain frozen under `results/calibration/{arcface,facenet}_lfw_v1/`.",
        "", "## Sources and integrity", "",
        "`models/checkpoint_manifest.json` records upstream links, model source commits, preprocessing, use restrictions and local checkpoint hashes. For author-hosted AdaFace/MagFace weights, hashes were measured locally; no independent upstream file digest was published in the recorded source. A matching local digest proves file identity to the recorded artifact, not independent upstream authenticity. Checkpoint files remain outside Git. The source JSON does not record per-artifact update timestamps; the date above is the specification verification date, not an invented artifact creation date.",
        "",
        "| Model | Threshold artifact SHA-256 | Score/metadata source |",
        "| --- | --- | --- |",
    ]
    for name in NAMES:
        p = f"results/calibration/{name}_lfw_v2/thresholds.json"
        other = f"results/calibration/{name}_lfw_v2/metadata.json" if (ROOT / f"results/calibration/{name}_lfw_v2/metadata.json").exists() else "v2 split audit and v1 calibration metadata"
        lines.append(f"| {name} | `{sha(p)}` | `{other}` |")
    lines += ["", "MobileFaceNet and MagFace held-out FAR exceed the 1% train target; these are observed quality warnings, not grounds to retune on held-out pairs.", ""]
    return "\n".join(lines)


def experiment() -> str:
    c = load("results/transfer/lfw_attack_dev_20_four_method_v3/pgd_landmark_superpixel_mask/config.json")
    assert c["formal"] and c["identity_count"] == 20 and c["attack"] == "pgd_full"
    for runner in ("scripts/run_lfw_dev_v2.py", "scripts/run_lfw_two_phase_v4.py"):
        tree = ast.parse((ROOT / runner).read_text(encoding="utf-8"))
        constants = {}
        for node in tree.body:
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name) and target.id in {"EPS", "STEPS"}:
                        constants[target.id] = ast.literal_eval(node.value)
                    elif isinstance(target, ast.Tuple) and all(isinstance(x, ast.Name) for x in target.elts):
                        values = ast.literal_eval(node.value)
                        constants.update(zip((x.id for x in target.elts), values))
        if constants.get("EPS") != c["configured_epsilon"] or constants.get("STEPS") != c["steps"]:
            raise ValueError(f"{runner} runtime constants diverge from frozen v3 config")
    eps, steps = c["configured_epsilon"], c["steps"]
    return f"""# Experiment configuration

Generated by `scripts/generate_research_specs.py` from the frozen v3 method config and v2 split audit. Last verified: 2026-10-29. Protocols are versioned; this document does not silently apply new settings to old results.

## Frozen v3 Development 20 baseline

Authority: `results/transfer/lfw_attack_dev_20_four_method_v3/pgd_landmark_superpixel_mask/config.json`, method summaries and generation records. Pair source is `{c['split']}`. {c['identity_count']} identities, four methods: PGD Full, MI-FGSM, PGD Full + landmark/SLIC mask, MI-FGSM + mask. The v1 five-person runs and v2 20-person runs remain provenance inputs; v3 aggregation uses their frozen serialized artifacts. Only probe B is attacked, reference A stays fixed.

| Setting | Value |
| --- | --- |
| ε in [0,1] | {eps} ({eps*255:g}/255) |
| Steps | {steps} |
| PGD α | ε/steps = {eps/steps:.4g} |
| MI-FGSM α | ε/steps = {eps/steps:.4g} |
| MI-FGSM momentum μ | 1.0 in formal v3 |
| TV weight | {c['tv_weight']} |
| PGD objective | Minimize ArcFace cosine between clean probe B embedding and current adversarial probe embedding |
| MI-FGSM objective | Same self-reference cosine minimization; no random start |

ArcFace `buffalo_l` R50 is the white-box gradient surrogate. FaceNet VGGFace2 is the black-box transfer victim and does not contribute gradients. Input is LFW funneled RGB JPEG decoded by OpenCV as BGR; attack tensor is full-size RGB float in [0,255]. Each step uses InsightFace five-point face alignment to a differentiable 112×112 crop, ArcFace `(crop−127.5)/127.5`, and L2-normalized embeddings. The landmark/SLIC mask is computed from the clean probe and multiplies the image-space gradient before the update.

PGD update: `delta ← project_L∞(delta − α sign(gradient), ε×255)`. MI-FGSM update order: raw gradient → optional mask → per-image L1 normalization → `g_t = μ g_(t−1) + normalized_gradient` → `delta ← project_L∞(delta − α sign(g_t), ε×255)`. Pixel clipping is [0,255]; final B_adv is uint8 PNG. Evaluation reloads the same serialized PNG for ArcFace, FaceNet and perceptual metrics. This is the implementation order in `advface/attacks/pgd.py`, `advface/attacks/mi_fgsm.py`, and `scripts/run_lfw_two_phase_v4.py`.

## Expansion protocol v2 (proposed five-model benchmark)

The frozen v2 split audit defines 100 Development identities and 228 OOS identities. Five evaluation models are ArcFace, FaceNet, AdaFace R50, MobileFaceNet and MagFace iResNet100; their exact weights and preprocessing are in `models/checkpoint_manifest.json`. Calibration v2 thresholds are under `results/calibration/*_lfw_v2/`. Development 100 clean eligibility and a two-person PGD+Mask engineering smoke exist. The formal 100-person four-method benchmark has **not** run; `scripts/run_lfw_five_model_benchmark.py` currently fails closed on its timing gate. OOS 228 is held out. Do not cite the two-person smoke as efficacy.

Momentum ablation `scripts/run_momentum_mask_v2.py` is separate from v3 and uses μ ∈ {{0, 0.5}} for two allowlisted Development identities at the same ε, steps and mask. Its output is under `results/transfer/lfw_momentum_mask_v2/`; do not merge it into the formal v3 denominator.
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {ROOT / "docs/CALIBRATION_AND_THRESHOLDS.md": calibration(), ROOT / "docs/EXPERIMENT_CONFIG.md": experiment()}
    for path, value in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != value:
                raise SystemExit(f"stale research specification: {path}")
        else:
            path.write_text(value, encoding="utf-8")
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
